//! The files in `packaging/linux/` are exactly what `bp-platform` generates.
//!
//! A distribution package installs these files, and the running product
//! reasons about them: Set as Default skips its per-user `.desktop` entry
//! when the packaged one claims the same types. If the shipped file and the
//! generator disagree, that reasoning is about a file nobody ships. So the
//! comparison is byte for byte, and the fix is always to regenerate, never to
//! edit the file by hand.

use std::path::{Path, PathBuf};

use bp_platform::editor::desktop::packaged_assets;

const REGENERATE: &str = "run `cargo run -p bp-platform --example regenerate_linux_assets` and \
                          commit the result";

fn packaging() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packaging/linux")
}

#[test]
fn every_shipped_linux_asset_is_byte_for_byte_what_bp_platform_generates() {
    for asset in packaged_assets() {
        let path = packaging().join(&asset.file_name);
        let shipped = std::fs::read_to_string(&path).unwrap_or_else(|error| {
            panic!("{} is missing ({error}); {REGENERATE}", path.display())
        });
        assert!(
            shipped == asset.contents,
            "{} differs from what bp-platform generates; {REGENERATE}.\n\
             --- shipped\n{shipped}\n--- generated\n{}",
            path.display(),
            asset.contents
        );
    }
}

#[test]
fn packaging_linux_holds_no_generated_kind_of_file_the_generator_no_longer_makes() {
    // An id change leaves the old files behind otherwise, and a package
    // script globbing `*.desktop` would ship both.
    let expected: Vec<String> = packaged_assets().into_iter().map(|a| a.file_name).collect();
    for entry in std::fs::read_dir(packaging()).expect("packaging/linux exists") {
        let name = entry.expect("a readable entry").file_name();
        let name = name.to_string_lossy();
        if name.ends_with(".desktop") || name.ends_with(".xml") {
            assert!(
                expected.iter().any(|e| e == name.as_ref()),
                "packaging/linux/{name} is not generated by bp-platform; delete it, then \
                 {REGENERATE}"
            );
        }
    }
}

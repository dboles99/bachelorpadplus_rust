<#
.SYNOPSIS
    Build the BachelorPad+ per-user installer from an already-built release exe.

.DESCRIPTION
    Compiles packaging/windows/bachelorpad.iss with Inno Setup 6 (release plan
    M3-01, decision 18). The version comes from Cargo.toml through
    `cargo metadata`, never from this script. Nothing is built with cargo
    here: the caller (the release script, M3-03, or a person) passes the
    exe it built and will sign.

    Staged for ISCC in a temporary directory, and passed with /D:
      * the licence page text: both licence files, one after the other,
        because Inno Setup's licence page shows one file;
      * bpad.cmd with CRLF line endings, whatever the checkout did.

    The [Registry] section in the .iss is generated by bp-platform; the test
    crates/bp-platform/tests/windows_installer.rs checks it is current, and
    the release script runs the tests before this.

    Writes the installer's path to the pipeline, and nothing else, so a
    caller can capture it: $setup = ./Build-Installer.ps1 ...

.PARAMETER ExePath
    The release bachelorpad.exe to package.

.PARAMETER OutputDir
    Where the installer is written. Created if missing.

.PARAMETER IsccPath
    ISCC.exe. Otherwise ISCC on PATH, then the default Inno Setup 6 install
    locations.

.PARAMETER Version
    Overrides the version read from Cargo.toml. For a release script that
    has already read it; it must still match the exe's version resource.

.PARAMETER OutputBaseName
    The installer's file name without .exe. Default:
    BachelorPadPlus-<version>-windows-x64-setup

.EXAMPLE
    ./packaging/windows/Build-Installer.ps1 -ExePath target/release/bachelorpad.exe -OutputDir artifacts/releases/v1.0.0
#>
#Requires -Version 5.1
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string]$ExePath,
    [Parameter(Mandatory)][string]$OutputDir,
    [string]$IsccPath,
    [string]$Version,
    [string]$OutputBaseName
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'PackagingCommon.ps1')

function Find-Iscc {
    param([string]$Explicit)

    if ($Explicit) {
        if (Test-Path -LiteralPath $Explicit -PathType Leaf) {
            return (Resolve-Path -LiteralPath $Explicit).Path
        }
        throw "ISCC.exe not found at $Explicit"
    }
    $onPath = Get-Command -Name 'ISCC.exe', 'iscc' -CommandType Application -ErrorAction SilentlyContinue |
        Select-Object -First 1
    if ($onPath) { return $onPath.Source }

    # Inno Setup 6 installs machine-wide under Program Files (x86), or per
    # user under %LOCALAPPDATA%\Programs.
    $candidates = @(
        @(${env:ProgramFiles(x86)}, 'Inno Setup 6\ISCC.exe'),
        @($env:ProgramFiles, 'Inno Setup 6\ISCC.exe'),
        @($env:LOCALAPPDATA, 'Programs\Inno Setup 6\ISCC.exe')
    )
    foreach ($candidate in $candidates) {
        if (-not $candidate[0]) { continue }
        $path = Join-Path $candidate[0] $candidate[1]
        if (Test-Path -LiteralPath $path -PathType Leaf) { return $path }
    }
    throw ("Inno Setup 6 (ISCC.exe) not found. Install Inno Setup 6.3 or later " +
        "(winget install JRSoftware.InnoSetup), put ISCC.exe on PATH, or pass -IsccPath.")
}

$repoRoot = Get-RepoRoot
$exe = (Resolve-Path -LiteralPath $ExePath).Path
if (-not $Version) { $Version = Get-WorkspaceVersion -RepoRoot $repoRoot }
$numeric = ConvertTo-NumericVersion -Version $Version
Assert-ExeVersion -ExePath $exe -Version $Version
if (-not $OutputBaseName) { $OutputBaseName = "BachelorPadPlus-$Version-windows-x64-setup" }
$licences = Get-LicenceFiles -RepoRoot $repoRoot
$iscc = Find-Iscc -Explicit $IsccPath

New-Item -ItemType Directory -Force -Path $OutputDir | Out-Null
$output = (Resolve-Path -LiteralPath $OutputDir).Path
$staging = New-StagingDirectory
try {
    $licenceText = "BachelorPad+ is copyright (C) Daniel Boles and is available under either of`n" +
        "the two licences below, at your option (SPDX: MIT OR Apache-2.0).`n"
    foreach ($licence in $licences) {
        $licenceText += "`n==== $(Split-Path -Leaf $licence) ====`n`n" + [System.IO.File]::ReadAllText($licence)
    }
    $licenceFile = Join-Path $staging 'LICENCE.txt'
    Write-WindowsText -Path $licenceFile -Text $licenceText

    $bpad = Join-Path $staging 'bpad.cmd'
    Copy-BatchFile -Source (Join-Path $PSScriptRoot 'bpad.cmd') -Destination $bpad

    $arguments = @(
        "/DAppVersion=$Version",
        "/DAppVersionNumeric=$numeric",
        "/DSourceExe=$exe",
        "/DRepoRoot=$repoRoot",
        "/DLicenceFile=$licenceFile",
        "/DBpadCmd=$bpad",
        "/O$output",
        "/F$OutputBaseName",
        (Join-Path $PSScriptRoot 'bachelorpad.iss')
    )
    Write-Host "Building the installer for BachelorPad+ $Version with $iscc"
    & $iscc @arguments | Write-Host
    if ($LASTEXITCODE -ne 0) { throw "ISCC failed (exit code $LASTEXITCODE)" }
}
finally {
    Remove-Item -LiteralPath $staging -Recurse -Force -ErrorAction SilentlyContinue
}

$setup = Join-Path $output "$OutputBaseName.exe"
if (-not (Test-Path -LiteralPath $setup -PathType Leaf)) {
    throw "ISCC reported success but $setup is not there"
}
Get-Item -LiteralPath $setup
